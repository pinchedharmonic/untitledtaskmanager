-- Private, single-account task data with row-level access control.
create table if not exists public.task_lists (
  id uuid primary key,
  owner_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  name text not null check (length(trim(name)) between 1 and 80),
  icon_key text not null default 'general',
  sort_order bigint generated always as identity,
  created_at timestamptz not null default now(),Q
  updated_at timestamptz not null default now(),
  unique (id, owner_id),
  unique (owner_id, sort_order)
);

create unique index if not exists task_lists_owner_name_ci
  on public.task_lists (owner_id, lower(name));

create table if not exists public.tasks (
  id uuid primary key,
  owner_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  list_id uuid not null,
  title text not null check (length(trim(title)) between 1 and 500),
  priority smallint not null check (priority between 1 and 5),
  -- Generated by Postgres so simultaneous clients still get distinct add order.
  sort_order bigint generated always as identity,
  completed_at timestamptz,
  elapsed_seconds bigint not null default 0 check (elapsed_seconds >= 0),
  timer_started_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint tasks_list_owner_fk
    foreign key (list_id, owner_id)
    references public.task_lists (id, owner_id)
    on delete cascade
);

create index if not exists tasks_owner_list_priority_order
  on public.tasks (owner_id, list_id, priority desc, sort_order asc);

create or replace function public.set_updated_at()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.updated_at := pg_catalog.now();
  return new;
end;
$$;
revoke all on function public.set_updated_at() from public;

drop trigger if exists task_lists_set_updated_at on public.task_lists;
create trigger task_lists_set_updated_at
before update on public.task_lists
for each row execute function public.set_updated_at();

drop trigger if exists tasks_set_updated_at on public.tasks;
create trigger tasks_set_updated_at
before update on public.tasks
for each row execute function public.set_updated_at();

alter table public.task_lists enable row level security;
alter table public.tasks enable row level security;

drop policy if exists "Users manage their own task lists" on public.task_lists;
create policy "Users manage their own task lists"
  on public.task_lists for all to authenticated
  using ((select auth.uid()) = owner_id)
  with check ((select auth.uid()) = owner_id);

drop policy if exists "Users manage their own tasks" on public.tasks;
create policy "Users manage their own tasks"
  on public.tasks for all to authenticated
  using ((select auth.uid()) = owner_id)
  with check ((select auth.uid()) = owner_id);

grant select, insert, update, delete on public.task_lists to authenticated;
grant select, insert, update, delete on public.tasks to authenticated;

create or replace function public.server_now()
returns timestamptz
language plpgsql
security invoker
set search_path = ''
as $$
begin
  if auth.uid() is null then raise exception 'Sign in is required'; end if;
  return pg_catalog.clock_timestamp();
end;
$$;
revoke all on function public.server_now() from public;
grant execute on function public.server_now() to authenticated;

-- Seed the three prototype lists once per account; subsequent launches do not
-- recreate lists that the user has renamed or deleted.
create or replace function public.ensure_default_task_lists()
returns void
language plpgsql
security invoker
set search_path = ''
as $$
begin
  if auth.uid() is null then
    raise exception 'Sign in is required';
  end if;

  if not exists (
    select 1 from public.task_lists where owner_id = auth.uid()
  ) then
    insert into public.task_lists (id, owner_id, name, icon_key)
    values
      (pg_catalog.gen_random_uuid(), auth.uid(), 'Work', 'work'),
      (pg_catalog.gen_random_uuid(), auth.uid(), 'Dojo', 'karate'),
      (pg_catalog.gen_random_uuid(), auth.uid(), 'Home', 'home')
    on conflict do nothing;
  end if;
end;
$$;
revoke all on function public.ensure_default_task_lists() from public;
grant execute on function public.ensure_default_task_lists() to authenticated;

-- Timer changes happen against the server's clock and return the accepted row.
create or replace function public.start_task_timer(p_task_id uuid)
returns public.tasks
language plpgsql
security invoker
set search_path = ''
as $$
declare saved public.tasks;
begin
  update public.tasks
     set timer_started_at = pg_catalog.clock_timestamp()
   where id = p_task_id
     and owner_id = auth.uid()
     and completed_at is null
     and timer_started_at is null
  returning * into saved;

  if not found then raise exception 'Task is missing, completed, or already running'; end if;
  return saved;
end;
$$;
revoke all on function public.start_task_timer(uuid) from public;
grant execute on function public.start_task_timer(uuid) to authenticated;

create or replace function public.pause_task_timer(p_task_id uuid)
returns public.tasks
language plpgsql
security invoker
set search_path = ''
as $$
declare saved public.tasks;
begin
  update public.tasks
     set elapsed_seconds = elapsed_seconds +
           greatest(0, floor(extract(epoch from (pg_catalog.clock_timestamp() - timer_started_at)))::bigint),
         timer_started_at = null
   where id = p_task_id
     and owner_id = auth.uid()
     and timer_started_at is not null
  returning * into saved;

  if not found then raise exception 'Task is missing or its timer is paused'; end if;
  return saved;
end;
$$;
revoke all on function public.pause_task_timer(uuid) from public;
grant execute on function public.pause_task_timer(uuid) to authenticated;

create or replace function public.set_task_completed(p_task_id uuid, p_completed boolean)
returns public.tasks
language plpgsql
security invoker
set search_path = ''
as $$
declare saved public.tasks;
begin
  update public.tasks
     set elapsed_seconds = elapsed_seconds + case
           when p_completed and timer_started_at is not null
           then greatest(0, floor(extract(epoch from (pg_catalog.clock_timestamp() - timer_started_at)))::bigint)
           else 0
         end,
         timer_started_at = case when p_completed then null else timer_started_at end,
         completed_at = case when p_completed then pg_catalog.clock_timestamp() else null end
   where id = p_task_id
     and owner_id = auth.uid()
  returning * into saved;

  if not found then raise exception 'Task not found'; end if;
  return saved;
end;
$$;
revoke all on function public.set_task_completed(uuid, boolean) from public;
grant execute on function public.set_task_completed(uuid, boolean) to authenticated;

-- Realtime is used only as a notification channel; clients reload authoritative
-- rows after an event. Add the tables idempotently for migration re-runs.
do $$
begin
  if not exists (
    select 1 from pg_catalog.pg_publication_tables
     where pubname = 'supabase_realtime' and schemaname = 'public' and tablename = 'task_lists'
  ) then alter publication supabase_realtime add table public.task_lists; end if;
  if not exists (
    select 1 from pg_catalog.pg_publication_tables
     where pubname = 'supabase_realtime' and schemaname = 'public' and tablename = 'tasks'
  ) then alter publication supabase_realtime add table public.tasks; end if;
end;
$$;
